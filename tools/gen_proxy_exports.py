"""Generates src/proxy_exports.h: linker directives that forward every export of the
system winmm.dll, so the mod can be dropped next to the game as winmm.dll.

Usage: python tools/gen_proxy_exports.py
"""
import os
import re
import subprocess

DUMPBIN = r'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Tools\MSVC\14.44.35207\bin\Hostx64\x64\dumpbin.exe'
DLL = 'winmm'
SYSTEM_DLL = os.path.join(os.environ.get('SystemRoot', r'C:\Windows'), 'System32', DLL + '.dll')
# Forward through the NT object namespace so the path doesn't depend on the drive Windows lives on.
TARGET = '\\\\.\\GLOBALROOT\\SystemRoot\\System32\\' + DLL

out = subprocess.run([DUMPBIN, '/nologo', '/exports', SYSTEM_DLL], capture_output=True, text=True, check=True).stdout
rows = []
for line in out.splitlines():
    m = re.match(r'\s+(\d+)\s+(?:[0-9A-F]+\s+)?[0-9A-F]{8}\s+(\S+)', line)
    if m:
        rows.append((int(m.group(1)), m.group(2)))

here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, '..', 'src', 'proxy_exports.h')
with open(dst, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_proxy_exports.py from %s. Do not edit.\n' % SYSTEM_DLL)
    f.write('// Every export forwards to the real system DLL.\n#pragma once\n\n')
    for ordinal, name in rows:
        esc = TARGET.replace('\\', '\\\\')
        if name == '[NONAME]':
            f.write('#pragma comment(linker, "/export:__proxy_ord%d=%s.#%d,@%d,NONAME")\n' % (ordinal, esc, ordinal, ordinal))
        else:
            f.write('#pragma comment(linker, "/export:%s=%s.%s,@%d")\n' % (name, esc, name, ordinal))
print('wrote %d exports to %s' % (len(rows), os.path.normpath(dst)))
